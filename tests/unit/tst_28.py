def run(prefix = "qrefine_"+os.path.basename(__file__).replace(".py","")):
  """
  Optimization: make sure freeze and exclude DO NOT move the same atoms
  """
  os.makedirs(prefix, exist_ok=True)
  os.chdir(prefix)
  #
  pdb_in = "%s.pdb"%prefix
  with open(pdb_in, "w") as fo:
    fo.write(pdb_str)
  m_start = mmtbx.model.manager(
    model_input = iotbx.pdb.input(file_name = pdb_in),
    log         = null_out())
  sel_moving = m_start.selection(string="resname ZZY")
  #
  r_freeze = run_qrefine(prefix = prefix, args=[pdb_in,
    "restraints=cctbx", "clustering=false", "number_of_micro_cycles=5",
    "freeze.selection='resname ZZY'", "level=0"])
  m_freeze = r_freeze.model
  #
  r_exclude = run_qrefine(prefix = prefix, args=[pdb_in,
    "restraints=cctbx", "clustering=false", "number_of_micro_cycles=5",
    "exclude='not (resname ZZY)'"])
  m_exclude = r_exclude.model
  # check results
  s1 = m_start.get_sites_cart().select(~sel_moving)
  s2 = m_freeze.get_sites_cart().select(~sel_moving)
  s3 = m_exclude.get_sites_cart().select(~sel_moving)
  for i, a in enumerate([s1,s2,s3]):
    for j, b in enumerate([s1,s2,s3]):
      if i==j: continue
      assert flex.mean(flex.sqrt((a - b).dot())) < 1.e-4
  #
  s1 = m_start.get_sites_cart().select(sel_moving)
  s2 = m_freeze.get_sites_cart().select(sel_moving)
  s3 = m_exclude.get_sites_cart().select(sel_moving)
  assert flex.mean(flex.sqrt((s1 - s2).dot())) > 0.2
  assert flex.mean(flex.sqrt((s1 - s3).dot())) > 0.2
  assert flex.mean(flex.sqrt((s2 - s3).dot())) > 0.2

if(__name__ == "__main__"):
  run()
